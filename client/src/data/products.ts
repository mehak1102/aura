function primary(url: string, alt: string) {
  return [{ url, alt, type: 'image' as const, isPrimary: true }]
}

function gallery(items: { url: string; alt: string }[]) {
  return items.map((item) => ({ ...item, type: 'image' as const }))
}

function variant(
  id: string,
  mrp: number,
  stock: number,
  size: string,
) {
  return [
    {
      id,
      name: size,
      sku: id.toUpperCase(),
      mrp,
      price: mrp,
      discountPercent: 0,
      stock,
      size,
    },
  ]
}

